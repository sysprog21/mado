#!/usr/bin/env python3
"""Generate unrolled affine composition from its dimensions.

Like b3d's math generator, emit ordinary C for compile-time optimization.
Each product is quantized separately: do not reassociate fixed products.
"""
import argparse
from decimal import Decimal, ROUND_HALF_UP, localcontext
from pathlib import Path


def neon():
    """Two columns per SIMD operation; integer addition follows each rounding."""
    lines = ['#include <arm_neon.h>', '',
             'static inline int32x2_t twin_math_neon_product(float32x2_t a, float32x2_t b)',
             '{', '    return vcvtm_s32_f32(vmul_f32(a, b));', '}', '',
             'static inline void twin_math_compose(twin_matrix_t *result,',
             '                                     const twin_matrix_t *a,',
             '                                     const twin_matrix_t *b)', '{',
             '    float32x2_t b0 = vcvt_n_f32_s32(vld1_s32(b->m[0]), 16);',
             '    float32x2_t b1 = vcvt_n_f32_s32(vld1_s32(b->m[1]), 16);',
             '    int32x2_t bt = vld1_s32(b->m[2]);']
    for row in range(3):
        lines.extend([f'    float32x2_t a{row} = vcvt_f32_s32(vld1_s32(a->m[{row}]));',
                      f'    int32x2_t p{row} = twin_math_neon_product(vdup_lane_f32(a{row}, 0), b0);',
                      f'    int32x2_t q{row} = twin_math_neon_product(vdup_lane_f32(a{row}, 1), b1);'])
        if row == 2:
            lines.append(f'    p{row} = vadd_s32(bt, p{row});')
        lines.append(f'    int32x2_t r{row} = vadd_s32(p{row}, q{row});')
    for row in range(3):
        lines.append(f'    vst1_s32(result->m[{row}], r{row});')
    lines.extend(['}', '',
                  'static inline void twin_math_translate(twin_matrix_t *m,',
                  '                                       twin_fixed_t tx, twin_fixed_t ty)', '{',
                  '    float32x2_t x = vcvt_f32_s32(vdup_n_s32(tx));',
                  '    float32x2_t y = vcvt_f32_s32(vdup_n_s32(ty));',
                  '    int32x2_t p = twin_math_neon_product(x, vcvt_n_f32_s32(vld1_s32(m->m[0]), 16));',
                  '    int32x2_t q = twin_math_neon_product(y, vcvt_n_f32_s32(vld1_s32(m->m[1]), 16));',
                  '    vst1_s32(m->m[2], vadd_s32(vadd_s32(vld1_s32(m->m[2]), p), q));', '}', '',
                  'static inline void twin_math_scale(twin_matrix_t *m,',
                  '                                   twin_fixed_t sx, twin_fixed_t sy)', '{'])
    for row, factor in [(0, 'sx'), (1, 'sy')]:
        lines.extend([f'    float32x2_t s{row} = vcvt_f32_s32(vdup_n_s32({factor}));',
                      f'    float32x2_t b{row} = vcvt_n_f32_s32(vld1_s32(m->m[{row}]), 16);',
                      f'    vst1_s32(m->m[{row}], twin_math_neon_product(s{row}, b{row}));'])
    lines.extend(['}', '',
                  'static inline void twin_math_rotate(twin_matrix_t *m,',
                  '                                    twin_fixed_t c, twin_fixed_t s)', '{',
                  '    float32x2_t cv = vcvt_f32_s32(vdup_n_s32(c));',
                  '    float32x2_t sv = vcvt_f32_s32(vdup_n_s32(s));',
                  '    float32x2_t b0 = vcvt_n_f32_s32(vld1_s32(m->m[0]), 16);',
                  '    float32x2_t b1 = vcvt_n_f32_s32(vld1_s32(m->m[1]), 16);',
                  '    int32x2_t r0 = vadd_s32(twin_math_neon_product(cv, b0),',
                  '                           twin_math_neon_product(sv, b1));',
                  '    int32x2_t r1 = vadd_s32(twin_math_neon_product(vneg_f32(sv), b0),',
                  '                           twin_math_neon_product(cv, b1));',
                  '    vst1_s32(m->m[0], r0);', '    vst1_s32(m->m[1], r1);', '}', '',
                  'static inline int32x2_t twin_math_transform_pair(const twin_matrix_t *m,',
                  '                                                twin_fixed_t x, twin_fixed_t y)', '{',
                  '    float32x2_t xv = vcvt_f32_s32(vdup_n_s32(x));',
                  '    float32x2_t yv = vcvt_f32_s32(vdup_n_s32(y));',
                  '    int32x2_t p = twin_math_neon_product(xv, vcvt_n_f32_s32(vld1_s32(m->m[0]), 16));',
                  '    int32x2_t q = twin_math_neon_product(yv, vcvt_n_f32_s32(vld1_s32(m->m[1]), 16));',
                  '    return vadd_s32(vadd_s32(p, q), vld1_s32(m->m[2]));', '}', ''])
    return lines


def generate():
    lines = ['/* Generated by scripts/gen-math.py; do not edit. */',
             '/* clang-format off */',
             '#ifndef TWIN_MATH_GEN_H', '#define TWIN_MATH_GEN_H',
             '#include "twin.h"', '',
             '#if TWIN_MATH_A64_NEON']
    lines += neon() + ['#else']
    lines += ['static inline void twin_math_compose(twin_matrix_t *result,',
             '                                     const twin_matrix_t *a,',
             '                                     const twin_matrix_t *b)',
             '{', '    twin_matrix_t r;']
    for row in range(3):
        for col in range(2):
            terms = [f'twin_fixed_mul(a->m[{row}][{n}], b->m[{n}][{col}])'
                     for n in range(2)]
            if row == 2:
                terms.insert(0, f'b->m[2][{col}]')
            lines.append(f'    r.m[{row}][{col}] =')
            lines.append('        ' + ' +\n        '.join(terms) + ';')
    lines.extend(['    *result = r;', '}', ''])
    # Structural zeros/ones are removed before C emission. This matters when
    # a backend's scalar conversion uses inline ASM and cannot be folded away.
    lines.extend(['static inline void twin_math_translate(twin_matrix_t *m,',
                  '                                       twin_fixed_t tx,',
                  '                                       twin_fixed_t ty)', '{'])
    for col in range(2):
        lines.extend([f'    twin_fixed_t t{col} = m->m[2][{col}] +',
                      f'        twin_fixed_mul(tx, m->m[0][{col}]) +',
                      f'        twin_fixed_mul(ty, m->m[1][{col}]);'])
    lines.extend(['    m->m[2][0] = t0;', '    m->m[2][1] = t1;', '}', ''])
    lines.extend(['static inline void twin_math_scale(twin_matrix_t *m,',
                  '                                   twin_fixed_t sx,',
                  '                                   twin_fixed_t sy)', '{'])
    for row, factor in [(0, 'sx'), (1, 'sy')]:
        for col in range(2):
            lines.append(f'    m->m[{row}][{col}] = '
                         f'twin_fixed_mul({factor}, m->m[{row}][{col}]);')
    lines.extend(['}', '',
                  'static inline void twin_math_rotate(twin_matrix_t *m,',
                  '                                    twin_fixed_t c,',
                  '                                    twin_fixed_t s)', '{'])
    for row, factors in [(0, ('c', 's')), (1, ('-s', 'c'))]:
        for col in range(2):
            lines.extend([f'    twin_fixed_t t{row}{col} =',
                          f'        twin_fixed_mul({factors[0]}, m->m[0][{col}]) +',
                          f'        twin_fixed_mul({factors[1]}, m->m[1][{col}]);'])
    for row in range(2):
        for col in range(2):
            lines.append(f'    m->m[{row}][{col}] = t{row}{col};')
    lines.extend(['}', '', '#endif', '#endif', '/* clang-format on */', ''])
    return '\n'.join(lines)


def sine_quarter():
    """Nearest Q16 sine samples; host libm and target FPU are unnecessary.

    Evaluate the Taylor series in 80-digit decimal arithmetic. This is far
    beyond the precision needed to decide rounding for these 1025 samples.
    Only the generated integer constants enter the target binary.
    """
    values = []
    with localcontext() as context:
        context.prec = 80
        pi = Decimal('3.14159265358979323846264338327950288419716939937510'
                     '5820974944592307816406286208998628')
        for x in range(1025):
            if x in (0, 1024):
                values.append(0 if x == 0 else 65536)
                continue
            angle = pi * x / 2048
            term = total = angle
            for n in range(1, 100):
                term *= -angle * angle / ((2 * n) * (2 * n + 1))
                updated = total + term
                if updated == total:
                    break
                total = updated
            else:
                raise RuntimeError('Sine series did not converge')
            values.append(int((total * 65536).to_integral_value(rounding=ROUND_HALF_UP)))
    lines = ['/* Generated by scripts/gen-math.py; do not edit. */',
             '/* clang-format off */',
             'static const twin_fixed_t twin_math_sin_quarter[1025] = {']
    for start in range(0, len(values), 8):
        lines.append('    ' + ', '.join(map(str, values[start:start + 8])) + ',')
    lines.extend(['};', '/* clang-format on */', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('-o', '--output', type=Path, required=True)
    parser.add_argument('--trig-table', action='store_true')
    args = parser.parse_args()
    content = sine_quarter() if args.trig_table else generate()
    # Make calls us only when a dependency changed. Refresh the timestamp even
    # if that change affected only the other generated output.
    args.output.write_text(content)
